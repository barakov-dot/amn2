from __future__ import annotations

from dataclasses import dataclass
from typing import Literal


SurfaceName = Literal["web", "public-token", "bot", "local-agent", "cli", "remote-operation"]
RiskClass = Literal[
    "auth-entry",
    "auth-exit",
    "read-only",
    "secret-adjacent-read",
    "secret-read",
    "public-token-entry",
    "public-token-state-write",
    "public-token-secret-read",
    "state-write",
    "remote-read",
    "remote-exec",
    "destructive",
]
SecretClass = Literal[
    "none",
    "secret-adjacent",
    "client-config-secret",
    "token-raw-issue",
    "public-token",
    "operation-output",
]
ImplementationMode = Literal["inventory-only", "blocked-future"]


class SurfacePolicyError(ValueError):
    pass


@dataclass(frozen=True)
class SurfacePolicy:
    policy_id: str
    surface: SurfaceName
    method: str
    path: str
    actor: str
    auth_method: str
    risk_class: RiskClass
    secret_class: SecretClass
    side_effects: tuple[str, ...]
    gates: tuple[str, ...]
    audit_required: bool
    operation_contract: str
    live_retest_required: bool
    implementation_mode: ImplementationMode
    enables_new_behavior: bool
    test_refs: tuple[str, ...]
    notes: str


def _p(
    policy_id: str,
    surface: SurfaceName,
    method: str,
    path: str,
    actor: str,
    auth_method: str,
    risk_class: RiskClass,
    secret_class: SecretClass,
    side_effects: tuple[str, ...],
    gates: tuple[str, ...],
    audit_required: bool,
    operation_contract: str,
    live_retest_required: bool,
    implementation_mode: ImplementationMode,
    test_refs: tuple[str, ...],
    notes: str,
) -> SurfacePolicy:
    return SurfacePolicy(
        policy_id=policy_id,
        surface=surface,
        method=method,
        path=path,
        actor=actor,
        auth_method=auth_method,
        risk_class=risk_class,
        secret_class=secret_class,
        side_effects=side_effects,
        gates=gates,
        audit_required=audit_required,
        operation_contract=operation_contract,
        live_retest_required=live_retest_required,
        implementation_mode=implementation_mode,
        enables_new_behavior=False,
        test_refs=test_refs,
        notes=notes,
    )


